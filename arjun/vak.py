def default_mount_paths() -> list[Path]:
    """Where a mounted sovereign vault might live, across OSes."""
    import os
    home = Path.home()
    candidates = [
        home / ".kernel-arjun" / "vault",
        Path("/Volumes/ÆmmaVault"),        # macOS external
        Path("/media") ,                    # Linux
    ]
    if os.name == "nt":
        candidates.append(Path("D:/ÆmmaVault"))
    return candidates


def find_vault(start: str | Path | None = None) -> Path | None:
    """Find an attached VĀK vault: an explicit path, or a known mount point."""
    if start:
        p = Path(start).expanduser()
        if p.is_file():
            return p
        if p.is_dir() and (p / "mind.vak").exists():
            return p / "mind.vak"
    for base in default_mount_paths():
        for name in ("mind.vak", "vault.vak", "æmma.vak"):
            if base.is_file():
                return base
            cand = base / name
            if cand.exists():
                return cand
    return None
